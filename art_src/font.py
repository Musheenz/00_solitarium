FONT = dict(GLYPHS)
FONT.pop('0', None)
FONT.update({k: v.split('|') for k, v in EXTRA.items()})
FONT['0'] = FONT['O']
FONT['Q'] = GLYPHS['Q']
H = 10
SPACING = 1   # font pixels between glyphs

def text_width(s, spacing=SPACING):
    return sum(len(FONT[c][0]) for c in s) + spacing * (len(s) - 1)

def render(s, color=(255,255,255,255), spacing=SPACING, scale=1):
    img = Image.new('RGBA', (text_width(s, spacing) * scale, H * scale), (0,0,0,0))
    px = img.load(); x = 0
    for c in s:
        g = FONT[c]
        for j, row in enumerate(g):
            for i, ch in enumerate(row):
                if ch == '#':
                    for a in range(scale):
                        for b in range(scale): px[(x+i)*scale + a, j*scale + b] = color
        x += len(g[0]) + spacing
    return img

def atlas():
    chars = ''.join(sorted(FONT))
    total = sum(len(FONT[c][0]) for c in chars) + len(chars)
    img = Image.new('RGBA', (total, H), (0,0,0,0)); px = img.load()
    meta = {'height': H, 'spacing': SPACING, 'glyphs': {}}
    x = 0
    for c in chars:
        g = FONT[c]; w = len(g[0])
        for j, row in enumerate(g):
            for i, ch in enumerate(row):
                if ch == '#': px[x+i, j] = (255,255,255,255)
        meta['glyphs'][c] = {'x': x, 'w': w}
        x += w + 1
    return img, meta

